import math


def area(r):

    """
    Вычисляет площадь круга по радиусу r.

    Параметры:
    r - неотрицательный радиус круга.

    Вывод: площадь круга.


    """

    if r < 0:
        raise ValueError("Радиус не может быть отрицательным")
    return math.pi * r * r


def perimeter(r):

    """
    Вычисляет периметр круга по радиусу r.

    Параметры:
    r - неотрицательный радиус круга.

    Вывод: периметр круга.

    """
    if r < 0:
        raise ValueError("Радиус не может быть отрицательным")
    return 2 * math.pi * r
