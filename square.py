
def area(a):
    """
    Вычисляет площадь квадрата по длине стороны a.
    Параметры:
    a - неотрицательная длина стороны квадрата.

    Вывод: площадь квадрата.
    """
    if a < 0:
        raise ValueError("Длина стороны не может быть отрицательной")
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине стороны a.

    Параметры:
    a - неотрицательная длина стороны квадрата.

    Вывод: периметр квадрата.
    """
    if a < 0:
        raise ValueError("Длина стороны не может быть отрицательной")
    return 4 * a
